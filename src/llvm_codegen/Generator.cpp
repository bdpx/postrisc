const char *ValueType2Str(ValueType type)
{
    switch (type) {
      case BOOL: return "bool";
      case VOID: return "void";
      case PVOID: return "PVOID";
      case IB: return "i8";
      case UB: return "u8";
      case IH: return "i16";
      case UH: return "u16";
      case IW: return "i32";
      case UW: return "u32";
      case ID: return "i64";
      case UD: return "u64";
      case IQ: return "i128";
      case UQ: return "u128";
      case FH: return "f16";
      case FS: return "f32";
      case FD: return "f64";
      case FQ: return "f128";
      case FX: return "F128";
      case VIB: return "v16i8";
      case VIH: return "v8i16";
      case VIW: return "v4i32";
      case VID: return "v2i64";
      case VUB: return "v16u8";
      case VUH: return "v8u16";
      case VUW: return "v4u32";
      case VUD: return "v2u64";
      case VFH: return "v8f16";
      case VFS: return "v4f32";
      case VFD: return "v2f64";
    }
    assert(!"unknown ValueType");
    return nullptr;
}


